#!/usr/bin/env node
import { spawn } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const DEFAULT_STACK_PROJECT = 'memries-e2e';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const e2eRoot = dirname(scriptsDir);
const composeFile = join(e2eRoot, 'docker-compose.yml');
const configFile = join(e2eRoot, '.work', 'memries.yaml');

/**
 * The disposable stack's own session key. Pinned like the bootstrap
 * password, and for the same reason: a developer's real key must not reach a
 * throwaway stack, and the suite must not depend on their machine having one
 * (ADR 0012, ADR 0028).
 */
const E2E_SESSION_KEY = 'ZTJlLXNlc3Npb24ta2V5LWZvci10ZXN0cy1vbmx5ISE=';

/**
 * The server reads one YAML file and nothing else (ADR 0028), but the stack's
 * public URL depends on the port this run leased, so the file is written per
 * run rather than committed.
 *
 * The admin list is pinned and kept in sync with scripts/owners.mjs: one
 * account per Playwright worker, because /api/e2e/reset is owner-scoped and a
 * shared account meant one worker's teardown wiped another's albums.
 */
export function renderConfig(publicUrl) {
  return `# Generated by scripts/stack.mjs for the E2E stack. Do not edit.
server:
  addr: ":8080"
  public_url: ${publicUrl}
  session_key: "${E2E_SESSION_KEY}"
  e2e: true

database:
  driver: sqlite
  dsn: /data/db/memries.db

library:
  roots:
    - /data/photos
  cache: /data/cache

admins:
  emails:
    - admin@example.com
    - worker-1@example.com
    - worker-2@example.com
    - worker-3@example.com
  bootstrap_password: "password"
`;
}

export const DEFAULT_PORTS = {
  caddy: 18080,
  backend: 18081,
  frontend: 15173,
};

function envPort(env, name, fallback) {
  const raw = env[name];
  const n = raw == null || raw === '' ? NaN : Number(raw);
  return Number.isInteger(n) && n > 0 ? n : fallback;
}

/** @param {NodeJS.ProcessEnv | Record<string, string | undefined>} env */
export function resolveStackConfig(env = process.env) {
  const ports = {
    caddy: envPort(env, 'CADDY_HOST_PORT', DEFAULT_PORTS.caddy),
    backend: envPort(env, 'BACKEND_HOST_PORT', DEFAULT_PORTS.backend),
    frontend: envPort(env, 'FRONTEND_HOST_PORT', DEFAULT_PORTS.frontend),
  };
  const origin = env.MEMRIES_E2E_ORIGIN || `http://localhost:${ports.caddy}`;
  const healthz = env.MEMRIES_E2E_HEALTHZ || `http://localhost:${ports.backend}/healthz`;
  return {
    project: env.MEMRIES_E2E_PROJECT || DEFAULT_STACK_PROJECT,
    ports,
    origin,
    healthz,
    publicUrl: origin,
    viteApiBase: origin,
    composeEnv: {
      CADDY_HOST_PORT: String(ports.caddy),
      BACKEND_HOST_PORT: String(ports.backend),
      FRONTEND_HOST_PORT: String(ports.frontend),
      MEMRIES_E2E_ORIGIN: origin,
    },
  };
}

/**
 * @param {ReturnType<typeof resolveStackConfig>} config
 * @param {string} composePath
 * @param {string[]} extra
 */
export function composeArgs(config, composePath, extra) {
  return ['compose', '-p', config.project, '-f', composePath, ...extra];
}

function run(cmd, args, env) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, {
      cwd: e2eRoot,
      env: { ...process.env, ...env },
      stdio: 'inherit',
    });
    child.on('error', reject);
    child.on('exit', (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${cmd} ${args.join(' ')} exited ${code}`));
    });
  });
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function waitFor(url, timeoutMs) {
  const start = Date.now();
  let lastErr = '';
  while (Date.now() - start < timeoutMs) {
    try {
      const res = await fetch(url, { redirect: 'manual' });
      if (res.ok || (res.status >= 300 && res.status < 400)) return;
      lastErr = `${res.status}`;
    } catch (err) {
      lastErr = err instanceof Error ? err.message : String(err);
    }
    await sleep(1000);
  }
  throw new Error(`Timed out waiting for ${url} (${lastErr})`);
}

async function dumpLogs(config) {
  try {
    await run(
      'docker',
      composeArgs(config, composeFile, ['logs', '--tail', '80']),
      config.composeEnv,
    );
  } catch {
    // ignore
  }
}

export async function up(options = {}) {
  const env = options.env ?? process.env;
  const config = resolveStackConfig(env);
  const runDocker = options.runDocker ?? run;
  try {
    if (!options.skipConfig) {
      mkdirSync(dirname(configFile), { recursive: true });
      writeFileSync(configFile, renderConfig(config.publicUrl), { mode: 0o600 });
    }
    if (!options.skipFixtures) {
      const fixtures = await import(pathToFileURL(join(scriptsDir, 'prepare-fixtures.mjs')).href);
      await fixtures.prepareAll();
    }
    await runDocker(
      'docker',
      composeArgs(config, composeFile, ['up', '-d', '--build']),
      config.composeEnv,
    );
    if (!options.skipWait) {
      await waitFor(config.origin, 170_000);
      await waitFor(config.healthz, 60_000);
    }
  } catch (err) {
    if (!options.skipLogs) await dumpLogs(config);
    throw err;
  }
}

export async function down(wipe, options = {}) {
  const env = options.env ?? process.env;
  const config = resolveStackConfig(env);
  const runDocker = options.runDocker ?? run;
  const extra = wipe ? ['down', '-v', '--remove-orphans'] : ['down', '--remove-orphans'];
  await runDocker('docker', composeArgs(config, composeFile, extra), config.composeEnv);
}

const isMain = Boolean(process.argv[1]) && pathToFileURL(process.argv[1]).href === import.meta.url;

if (isMain) {
  const cmd = process.argv[2] ?? 'up';
  const wipe = process.argv.includes('--wipe');

  if (cmd === 'up') {
    await up();
    // Playwright's webServer expects a long-lived process; exiting right after `compose up -d`
    // races its own URL poll and fails with "exited early". Stay alive until it stops us.
    if (process.argv.includes('--hold')) {
      const keepAlive = setInterval(() => {}, 1 << 30);
      await new Promise((resolve) => {
        process.once('SIGTERM', resolve);
        process.once('SIGINT', resolve);
      });
      clearInterval(keepAlive);
    }
  } else if (cmd === 'down') {
    await down(wipe);
  } else {
    console.error('Usage: node scripts/stack.mjs <up [--hold]|down [--wipe]>');
    process.exit(1);
  }
}
